  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Item>
>(({ className, children, ...props }, ref) => (
  <SelectPrimitive.Item
    ref={ref}
    className={cn(
      "relative flex cursor-pointer select-none items-center rounded-md py-1.5 pl-7 pr-2 text-[13px]",
      "outline-none data-[highlighted]:bg-sunken data-[state=checked]:font-semibold",
      className,
    )}
    {...props}
  >
    <span className="absolute left-2 grid place-items-center">
      <SelectPrimitive.ItemIndicator><Check size={13} className="text-brand" /></SelectPrimitive.ItemIndicator>
    </span>
    <SelectPrimitive.ItemText>{children}</SelectPrimitive.ItemText>
  </SelectPrimitive.Item>
));
SelectItem.displayName = "SelectItem";
